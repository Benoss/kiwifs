/**
 * The fence catalogue as plain JSON.
 *
 * One file, three readers: the Go linter embeds it to check a fence on write,
 * `kiwi_widget_reference` serves it to agents, and `docs/WIDGETS.md` is
 * generated from it. A description written in a spec therefore appears
 * everywhere, and cannot drift between surfaces.
 */

import { registerBuiltinFences } from "./builtins";
import { allFences } from "./registry";
import { RESERVED_STEP, RESERVED_TOP_LEVEL, serializeSchema, type SerializedAttribute } from "./schema";

export interface FenceDoc {
  lang: string;
  aliases: string[];
  description: string;
  /** Any one of these keys marks a bare fence as belonging to this widget. */
  required: string[];
  example: string;
  attributes: Record<string, SerializedAttribute>;
}

export interface FenceCatalogue {
  /** Bumped when the shape of this file changes, not when a fence is added. */
  version: number;
  /** Keys every fence understands, stripped before the widget sees them. */
  reservedTopLevel: string[];
  /** Keys a step may carry that are not widget props. */
  reservedStep: string[];
  fences: FenceDoc[];
}

export function fenceCatalogue(): FenceCatalogue {
  registerBuiltinFences();
  const fences = allFences()
    .filter((spec) => !spec.legacy)
    .map<FenceDoc>((spec) => ({
      lang: spec.lang,
      aliases: [`kiwi-${spec.lang}`, `widget:${spec.lang}`, ...(spec.aliases ?? [])],
      description: spec.description,
      required:
        spec.required ??
        Object.entries(spec.schema.attributes)
          .filter(([, a]) => a.required)
          .map(([k]) => k),
      example: spec.example,
      attributes: serializeSchema(spec.schema),
    }))
    .sort((a, b) => a.lang.localeCompare(b.lang));

  return {
    version: 1,
    reservedTopLevel: [...RESERVED_TOP_LEVEL],
    reservedStep: [...RESERVED_STEP],
    fences,
  };
}

export function fenceCatalogueJSON(): string {
  return `${JSON.stringify(fenceCatalogue(), null, 2)}\n`;
}

// ── Reference page ──────────────────────────────────────────────────────────

function attributeRows(doc: FenceDoc): string {
  const names = Object.keys(doc.attributes).sort((a, b) => {
    const ra = doc.attributes[a]!.required ? 0 : 1;
    const rb = doc.attributes[b]!.required ? 0 : 1;
    return ra - rb || a.localeCompare(b);
  });
  // A bare `|` would end the table cell, and every union type contains one.
  const cell = (text: string) => text.replace(/\|/g, "\\|");
  const rows = names.map((name) => {
    const attr = doc.attributes[name]!;
    let type = attr.type.split("|").map((t) => `\`${t}\``).join(" or ");
    if (attr.items) type += ` of ${attr.items.split("|").map((t) => `\`${t}\``).join(" or ")}`;
    if (attr.matches) type = attr.matches.map((m) => `\`${m}\``).join(" or ");
    const flags = [
      attr.required ? "**required**" : "",
      attr.steppable === false ? "fixed across steps" : "",
    ].filter(Boolean);
    const notes = [attr.description ?? "", ...flags].filter(Boolean).join(" — ");
    return `| \`${name}\` | ${type} | ${cell(notes)} |`;
  });
  return ["| Key | Type | Notes |", "|---|---|---|", ...rows].join("\n");
}

/**
 * `docs/WIDGETS.md`, generated so it cannot drift from the schema the linter
 * enforces. Hand-written prose about *why* a widget exists belongs in
 * docs/EXAMPLES.md; this file is the reference.
 */
export function referenceMarkdown(): string {
  const cat = fenceCatalogue();
  const out: string[] = [];

  out.push("# Widget fences");
  out.push("");
  out.push("<!-- Generated by ui/scripts/emit-fence-schemas.mjs. Do not edit by hand. -->");
  out.push("");
  out.push(
    "Every picture in a KiwiFS page is data, not a program. You write a fenced block",
    "with a YAML body; KiwiFS validates it on write, renders it interactively, steps it",
    "on a clock a reader can link to, and degrades to readable text in `cat`, git, PDF",
    "and search.",
    "",
  );
  out.push("## Body grammar", "");
  out.push(
    "Top-level keys are the widget's properties. An optional `steps:` list holds one",
    "shallow patch per step, **each over the previous step**, so you write only what",
    "changes. `frames:` is the same list with each entry over the base instead.",
    "",
    "A step may also carry keys that are not widget properties:",
    "",
    "| Step key | Meaning |",
    "|---|---|",
    "| `note` | Prose shown under the picture for this step. |",
    "| `line` / `next` | 1-based line of `code:` to highlight. |",
    "| `label` | Name for this step in the transport. |",
    "| `why` | Key → explanation, revealed when the reader selects that part. |",
    "| `breakpoint` | Auto-play pauses here. |",
    "| `duration` | Milliseconds this step holds at 1×. |",
    "| `expect` | Pause until the reader selects the right part. |",
    "",
    "`code:` plus `lang:` render a listing that steps in lockstep. `props:` is the",
    "escape hatch for a widget property whose name collides with a reserved key.",
    "",
  );
  out.push("## Meta string", "");
  out.push(
    "Written after the language on the opening line:",
    "",
    "| Option | Meaning |",
    "|---|---|",
    "| `id=name` | Names the widget, its anchor, and its clock. |",
    "| `clock=name` | Shares a step counter with every other fence naming it. |",
    '| `caption="…"` | Caption under the figure. |',
    '| `title="…"` | Heading above it. |',
    "| `width=wide\\|full` | Figure width. |",
    "| `autoplay`, `loop` | Playback behaviour. |",
    "",
    "A reader links to a step as `#?step.<id>=N`; the first unnamed widget on a page",
    "owns the bare `#?step=N`.",
    "",
  );
  out.push("## Naming and collisions", "");
  out.push(
    "Each fence answers to three language tags: the bare name (`array`), the explicit",
    "`kiwi-array`, and the legacy `widget:array`. A bare name only claims a block whose",
    "YAML parses to a mapping carrying one of the fence's marker keys, so a vault that",
    "already uses `tree` for directory listings keeps its code blocks. The `kiwi-` and",
    "`widget:` spellings always render, or report an error, for authors who prefer",
    "strictness.",
    "",
    "`[ui] typed_fences = false` in `.kiwi/config.toml` turns bare tags off for a",
    "workspace; `typed_fence_tags = [\"array\", \"matrix\"]` allows only those.",
    "",
  );
  out.push("## Fences", "");
  out.push("| Fence | What it draws |", "|---|---|");
  for (const doc of cat.fences) {
    out.push(`| [\`${doc.lang}\`](#${doc.lang.replace(/[^a-z0-9]+/g, "-")}) | ${doc.description} |`);
  }
  out.push("");

  for (const doc of cat.fences) {
    out.push(`### ${doc.lang}`, "");
    out.push(doc.description, "");
    if (doc.required.length > 0) {
      out.push(
        `A bare \`${doc.lang}\` fence renders as a widget when its body carries ` +
          doc.required.map((k) => `\`${k}\``).join(" or ") +
          ".",
        "",
      );
    }
    out.push(`Also spelled: ${doc.aliases.map((a) => `\`${a}\``).join(", ")}.`, "");
    out.push(attributeRows(doc), "");
    out.push("````markdown", doc.example.replace(/\n$/, ""), "````", "");
  }

  out.push("## Reserved keys", "");
  out.push(
    "Handled by the fence platform, never passed to the widget:",
    "",
    `Top level: ${cat.reservedTopLevel.map((k) => `\`${k}\``).join(", ")}.`,
    "",
    `In a step: ${cat.reservedStep.map((k) => `\`${k}\``).join(", ")}.`,
    "",
  );

  return out.join("\n");
}
